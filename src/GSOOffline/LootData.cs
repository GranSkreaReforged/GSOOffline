using System;
using System.Collections.Generic;
using System.IO;

namespace GSOOffline
{
    [Serializable]
    public class LootDrop
    {
        public int typeId;
        public string name;
        public int min = 1, max = 1;
        public float chance;
        public List<int> levels = new List<int>();   // empty = every level of this NPC
        public string from;                          // where the wiki generator found it, e.g. "patch notes 139"
    }

    [Serializable]
    public class LootMonster
    {
        public string name;
        public bool dropsSilver;
        public List<int> silver = new List<int>();   // [min, max] from the wiki, empty = CombatRules.SilverDrop
        public List<LootDrop> drops = new List<LootDrop>();
    }

    [Serializable]
    public class LootFile
    {
        public List<LootMonster> monsters = new List<LootMonster>();
    }

    [Serializable]
    public class OriginalDrop
    {
        public int typeId;   // 0 = silver
        public string name;
        public int rate;     // 1 in rate
        public int min = 1, max = 1;
    }

    [Serializable]
    public class OriginalTable
    {
        public List<int> npcs = new List<int>();
        public string name;
        public List<OriginalDrop> drops = new List<OriginalDrop>();
    }

    [Serializable]
    public class OriginalLootFile
    {
        public List<int> originalNpcs = new List<int>();
        public List<OriginalTable> tables = new List<OriginalTable>();
    }

    /// <summary>
    /// NPC drop tables from Data/loot.json, generated by GSODevTools/tools/datamining/gen_loot.py from the
    /// community wiki (the server's own tables are lost). Monsters are matched by NPCInfo name.
    /// </summary>
    internal static class LootData
    {
        private static LootFile file;
        private static Dictionary<string, LootMonster> byName;

        public static LootFile File
        {
            get
            {
                if (file != null) return file;
                using (var s = typeof(LootData).Assembly.GetManifestResourceStream("GSOOffline.loot.json"))
                using (var r = new StreamReader(s))
                    file = Json.Deserialize<LootFile>(r.ReadToEnd());
                byName = new Dictionary<string, LootMonster>(StringComparer.OrdinalIgnoreCase);
                foreach (var m in file.monsters) byName[m.name.Trim()] = m;
                Plugin.Log.LogInfo($"[loot] {file.monsters.Count} wiki drop tables");
                return file;
            }
        }

        private static HashSet<int> originalNpcs;
        private static Dictionary<int, List<OriginalDrop>> originalDrops;

        /// <summary>
        /// Data/droptables.json: the original server's drop tables (Loot.xml, about update 136), generated by
        /// GSODevTools/tools/datamining/gen_droptables.py. An NPC can be in several tables; it rolls them all.
        /// </summary>
        private static void LoadOriginal()
        {
            if (originalDrops != null) return;
            OriginalLootFile f;
            using (var s = typeof(LootData).Assembly.GetManifestResourceStream("GSOOffline.droptables.json"))
            using (var r = new StreamReader(s))
                f = Json.Deserialize<OriginalLootFile>(r.ReadToEnd());
            originalNpcs = new HashSet<int>(f.originalNpcs);
            originalDrops = new Dictionary<int, List<OriginalDrop>>();
            foreach (var t in f.tables)
                foreach (int npc in t.npcs)
                {
                    if (!originalDrops.TryGetValue(npc, out var list)) originalDrops[npc] = list = new List<OriginalDrop>();
                    list.AddRange(t.drops);
                }
            Plugin.Log.LogInfo($"[loot] original server: {f.tables.Count} drop tables for {originalDrops.Count} NPC types");
        }

        /// <summary>Whether the original server knew this NPC type (it then dropped only from its own tables).</summary>
        public static bool KnownToOriginal(int npcType)
        {
            LoadOriginal();
            return originalNpcs.Contains(npcType);
        }

        /// <summary>The original server's drops for this NPC type; empty if it had none.</summary>
        public static List<OriginalDrop> OriginalDrops(int npcType)
        {
            LoadOriginal();
            return originalDrops.TryGetValue(npcType, out var list) ? list : new List<OriginalDrop>();
        }

        /// <summary>The wiki's table for this NPC name, or null if the wiki has none.</summary>
        public static LootMonster For(string npcName)
        {
            if (File == null || string.IsNullOrEmpty(npcName)) return null;
            return byName.TryGetValue(npcName.Trim(), out var m) ? m : null;
        }
    }
}
