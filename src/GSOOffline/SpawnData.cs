using System;
using System.Collections.Generic;
using System.IO;
using UnityEngine;

namespace GSOOffline
{
    [Serializable]
    public class SpawnRow
    {
        public int type, scene;
        public float[] pos;

        public Vector3 Position => new Vector3(pos[0], pos[1], pos[2]);
    }

    [Serializable]
    public class SpawnFile
    {
        public List<SpawnRow> npcs = new List<SpawnRow>();
        public List<SpawnRow> harvestables = new List<SpawnRow>();
    }

    /// <summary>
    /// Data/spawns.json: NPCs and harvestables the original server spawned where the client has no scene markers
    /// (most of Deepheart, a few NPCs elsewhere), generated by GSODevTools/tools/datamining/gen_spawns.py from its
    /// npcData_/harvestableData_ files. SceneWorld.Build adds them to the markers' spawns.
    /// </summary>
    internal static class SpawnData
    {
        private static SpawnFile file;

        private static SpawnFile File
        {
            get
            {
                if (file != null) return file;
                using (var s = typeof(SpawnData).Assembly.GetManifestResourceStream("GSOOffline.spawns.json"))
                using (var r = new StreamReader(s))
                    file = Json.Deserialize<SpawnFile>(r.ReadToEnd());
                Plugin.Log.LogInfo($"[world] {file.npcs.Count} NPC and {file.harvestables.Count} harvestable spawns from the original server");
                return file;
            }
        }

        public static IEnumerable<SpawnRow> Npcs(int scene)
        {
            foreach (var r in File.npcs) if (r.scene == scene) yield return r;
        }

        public static IEnumerable<SpawnRow> Harvestables(int scene)
        {
            foreach (var r in File.harvestables) if (r.scene == scene) yield return r;
        }
    }
}
